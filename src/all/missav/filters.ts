import { Filter, FilterList } from "../../../sdk/index.ts";

abstract class SelectFilter extends Filter.Select<string> {
  constructor(
    name: string,
    private readonly options: [string, string][],
  ) {
    super(
      name,
      options.map((it) => it[0]),
    );
  }
  get selected(): string | null {
    return this.state === 0 ? null : this.options[this.state][1];
  }
}

export class SortFilter extends SelectFilter {
  constructor() {
    super("Sort by", SORT);
  }
}

export class GenreList extends SelectFilter {
  constructor() {
    super("Genres", GENRES);
  }
}

