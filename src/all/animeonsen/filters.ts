export class GenreFilter extends Filter.Select<string> {
  constructor() {
    super(
      "Genre",
      GENRES.map((it) => it[0]),
      0,
    );
  }
  getValue() {
    return this.state === 0 ? null : GENRES[this.state][1];
  }
}

export const getFilterList = (): FilterList => FilterList(new GenreFilter());
