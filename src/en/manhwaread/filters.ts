export class TagsFilter extends Filter.Group<TriStateFilter> {
  constructor() {
    super(
      "Tags",
      tagsOptions.map(([n, v]) => new TriStateFilter(n, v)),
    );
  }
  readonly includedQueryName: string = "including[]";
  get includedQueryValues(): string[] {
    return this.state.filter((it) => it.isIncluded()).map((it) => it.value);
  }

  readonly excludedQueryName: string = "excluding[]";
  get excludedQueryValues(): string[] {
    return this.state.filter((it) => it.isExcluded()).map((it) => it.value);
  }
}

