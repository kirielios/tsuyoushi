export class SortByFilter extends Filter.Sort {
  static readonly options = new Map<string, string>([
    ["Release", "release"],
    ["New", "new"],
    ["A-Z", "alphabet"],
    ["Rating", "rating"],
    ["Bookmarks", "bookmarks"],
    ["Chapters", "chapters"],
    ["Comments", "comments"],
    ["Daily Views", "daily_top"],
    ["Weekly Views", "weekly_top"],
    ["Monthly Views", "monthly_top"],
    ["Yearly Views", "yearly_top"],
    ["All Time Views", "all_top"],
  ]);

  // companion object vals; getters so each use gets fresh filter state
  static get POPULAR(): FilterList {
    const f = new SortByFilter();
    f.state = { index: 8, ascending: false };
    return FilterList(f);
  }
  static get LATEST(): FilterList {
    const f = new SortByFilter();
    f.state = { index: 0, ascending: false };
    return FilterList(f);
  }

  constructor() {
    super("Sort By", [...SortByFilter.options.keys()], {
      index: 7,
      ascending: false,
    });
  }

  readonly queryName: string = "sortby";
  get queryValue(): string {
    return SortByFilter.options.get(this.values[this.state?.index ?? 0])!;
  }
  get orderValue(): string {
    return this.state?.ascending === true ? "asc" : "desc";
  }
}

abstract class MapSelectFilter extends Filter.Select<string> {
  constructor(
    name: string,
    private readonly options: Map<string, string>,
  ) {
    super(name, [...options.keys()]);
  }
  abstract readonly queryName: string;
  get queryValue(): string {
    return this.options.get(this.values[this.state])!;
  }
}

